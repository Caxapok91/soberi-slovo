# Теги OpenCorpora: слова, у которых ВСЕ разборы — имена собственные,
# геонимы, аббревиатуры и т.п. В игре они лишние.
PROPER_TAGS = ("Name", "Surn", "Patr", "Geox", "Orgn", "Abbr", "Pint", "Aspr")

# Оставляем только полноценные слова в начальной форме:
# существительные и прилагательные в именительном, инфинитивы,
# наречия, числительные. Падежные формы («нашим», «чьим») и
# обрывки («макао», «сити») в игре только мешают.
CONTENT_TAGS = ("NOUN", "ADJF", "VERB", "NUMR", "ADVB", "ADV", "INFN", "COMP")

# Короткие слова чаще всего — омонимы и обрывки («сити», «чьим»).
# Поэтому чем короче слово, тем выше требуемая частота в корпусе.
MIN_ZIPF = {3: 3.0, 4: 3.0, 5: 2.8, 6: 2.7, 7: 2.6, 8: 2.5, 9: 2.4}
DEFAULT_MIN_ZIPF = 2.3

# Омографы-осколки разрешаем только для очень частотных слов: среди
# них «вода», «лес», «море», но нет «пола», «тура», «пути��а».
HOMONYM_MIN_ZIPF = 3.6

# Сколько словоформ нужно у слова, чтобы считать его настоящим русским.
# У «стол» есть стол/стола/столу/столом/столе/столы, а у транслитераций
# («уокер», «логан») в корпусе встречается только сама форма.
MIN_FORMS = {3: 0, 4: 0}
DEFAULT_MIN_FORMS = 0

# Сколько словоформ держать для бонусов (падежи, времена).
MAX_FORMS = 20000


# Типичные фамильные окончания (для дополнительной фильтрации)
SURNAME_ENDINGS = (
    "ов", "ев", "ин", "ын", "ский", "ская", "цкий", "цкая",
    "ович", "евич", "ич", "овна", "евна", "ична",
    "енко", "ко", "ук", "юк", "як", "ак", "ик",
    "ский", "цкий", "ской", "цкой",
)

def looks_like_surname(word):
    """Эвристика: слово выглядит как фамилия."""
    w = word.lower()
    if len(w) < 4:
        return False
    for ending in SURNAME_ENDINGS:
        if w.endswith(ending):
            # Исключения: обычные слова на эти окончания
            if w in {"нов", "лев", "дев", "цев", "рыв", "лив", "зим", "вес", "лес", "гос", "кос", "нос", "рос", "лос", "мос", "тос", "пос", "бос", "дос", "пол", "зал", "мал", "бал", "гал", "дал", "кал", "пал", "сал", "тал", "хал", "шал", "ял"}:
                continue
            # Прилагательные на -ский/-ской тоже исключаем
            if ending in ("ский", "ская", "цкий", "цкая", "ской", "цкой") and len(w) > 5:
                return True
            # Существительные на -ов/-ев/-ин/-ын - скорее всего фамилии
            if ending in ("ов", "ев", "ин", "ын") and len(w) > 3:
                return True
    return False


def is_proper(tag):
    return any(t in tag for t in PROPER_TAGS)


def parse_ok(tag):
    """Подходит ли тег: только обычные полноценные слова."""
    if is_proper(tag):
        return False
    if "Acc" in tag or "PNC" in tag:      # сокращения, частицы
        return False
    return tag.startswith(CONTENT_TAGS)


def lemma_ok(morph, word, allow_homonym=False):
    """Слово — самостоятельное начальное слово, а не кусок другой формы.

    Строгий случай требует, чтобы КАЖДЫЙ разбор вёл к самому слову.
    Такие исключения, как «вода» (где есть ещё осколок «вод») или
    «лес» (где «леса» — род. п. мн. ч.), этому условию не удовлетворяют,
    хотя слова совершенно обычные. Для самых частотных слов разрешаем
    омографы: там мусора («пола», «тура», «путина») попросту нет.
    """
    # Быстрая эвристика: отсекаем слова, похожие на фамилии
    if looks_like_surname(word):
        return False

    parses = morph.parse(word)
    if not parses:
        return False

    # ни одного разбора как имя/геоним/сокращение — иначе обрывок формы
    # («пола» → «Ола», «мари» → «Мария», «путина» → «Путин»)
    if not any(parse_ok(str(p.tag)) for p in parses):
        return False
    if all(is_proper(str(p.tag)) for p in parses):
        return False

    own = [p for p in parses if parse_ok(str(p.tag)) and p.normal_form.lower() == word]
    if not own:
        return False

    if all(parse_ok(str(p.tag)) and p.normal_form.lower() == word for p in parses):
        return True

    # мягкий случай: слово самостоятельное, но где-то есть омоним-осколок
    return allow_homonym


def main():
    morph = pymorphy3.MorphAnalyzer()

    # 1. Леммы = слова, которые в корпусе встречаются САМИ в начальной форме.
    #    Так отсекаются обрывки форм: «гот», «кий», «пля» не существуют
    #    как отдельные слова, а «стол», «кот», «море» — существуют.
    #    Если у слова есть разбор как имя/геоним («пола» → «Ола»,
    #    «мари» → «Мария»), оно отбрасывается: это обрывок формы.
    freq = {}
    forms_seen = {}

    for w in top_n_list("ru", 600000):
        if not re.fullmatch(r"[а-яё]+", w):
            continue
        if "ё" in w or w in STOP:
            continue
        if not (MIN_LEN <= len(w) <= MAX_LEN):
            continue

        # Слово берём, только если оно «словарное»: это начальная форма
        # обычного слова, а не кусок чужой формы («тура» = мн. ч. «тур»).
        z = zipf_frequency(w, "ru")
        if not lemma_ok(morph, w, allow_homonym=z >= HOMONYM_MIN_ZIPF):
            continue

        freq[w] = z

    # 1b. Считаем, сколько разных словоформ есть у каждого слова.
    #     Настоящее русское слово живёт во всех падежах; транслитерация
    #     («уокер», «гранд») — только сама по себе.
    for w in top_n_list("ru", 600000):
        if not re.fullmatch(r"[а-яё]+", w) or not (MIN_LEN <= len(w) <= MAX_LEN):
            continue
        for p in morph.parse(w):
            if not parse_ok(str(p.tag)):
                continue
            lemma = p.normal_form.lower()
            if lemma in freq:
                forms_seen.setdefault(lemma, set()).add(w)
            break

    # 2. Отбираем по длине, частотности и наличию словоформ.
    by_len = {n: [] for n in range(MIN_LEN, MAX_LEN + 1)}

    for word, z in sorted(freq.items(), key=lambda kv: -kv[1]):
        length = len(word)
        if len(by_len[length]) >= LIMITS[length]:
            continue
        if len(forms_seen.get(word, ())) < MIN_FORMS.get(length, DEFAULT_MIN_FORMS):
            continue
        if z < MIN_ZIPF.get(length, DEFAULT_MIN_ZIPF):
            continue
        by_len[length].append(word)

    parts = []
    total = 0
    lemmas_all = []
    for length in sorted(by_len):
        chunk = by_len[length]
        total += len(chunk)
        lemmas_all.extend(chunk)
        # Пишем по 18 слов в строке: строки получаются короткими,
        # это надёжнее для парсеров JS, чем одна многотысячная строка.
        rows = []
        for i in range(0, len(chunk), 18):
            rows.append("    " + " ".join('"%s",' % w for w in chunk[i:i + 18]))
        parts.append("  %d: [\n%s\n  ]," % (length, "\n".join(rows)))

    # Последний элемент объекта запятой не заканчиваем.
    parts[-1] = parts[-1][:-1]

    # 3. Словоформы для бонусов: падежи и времена нужных слов.
    #    Если игрок нарисует «столы» вместо «стол» — слово засчитается.
    lemma_set = set(lemmas_all)
    forms = []
    seen_forms = set(lemmas_all)
    for w in top_n_list("ru", 400000):
        if not re.fullmatch(r"[а-яё]+", w):
            continue
        if not (MIN_LEN <= len(w) <= MAX_LEN) or w in seen_forms:
            continue
        for p in morph.parse(w):
            tag = str(p.tag)
            if parse_ok(tag) and p.normal_form.lower() in lemma_set:
                forms.append(w)
                seen_forms.add(w)
            break
        if len(forms) >= MAX_FORMS:
            break

    form_rows = []
    for i in range(0, len(forms), 18):
        form_rows.append("  " + " ".join('"%s",' % w for w in forms[i:i + 18]))

    header = """/* ============================================================
   СЛОВАРЬ (сгенерирован tools/build_words.py)
   WORDS — слова в начальной форме, из них собираются задания.
   FORMS — словоформы тех же слов, засчитываются как бонус.
   ============================================================ */

const WORDS_PACK = {
%s
};

/** Словоформы: «столы», «столом», «красивый» и т.п. */
const FORMS_PACK = [
%s
];

const MIN_WORD_LEN = %d;
const MAX_WORD_LEN = %d;

/** Словарь начальных форм: {длина: [слова]} */
const WORDS = WORDS_PACK;

/** Плоский список начальных форм. */
const ALL_WORDS = (function () {
  const list = [];
  for (const key of Object.keys(WORDS)) list.push.apply(list, WORDS[key]);
  return list;
})();

/** Set для проверки: начальные формы + их словоформы. */
const LEMMA_SET = new Set(ALL_WORDS);

/** Слова по длинам - быстрый поиск продолжений. */
const LEX_BY_LEN = (function () {
  const out = {};
  for (const key of Object.keys(WORDS)) out[key] = WORDS[key];
  return out;
})();

/** Set для проверки: начальные формы + их словоформы. */
const WORD_SET = new Set(ALL_WORDS.concat(FORMS_PACK));
""" % ("\n".join(parts), "\n".join(form_rows), MIN_LEN, MAX_LEN)


    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(header)

    print("Готово: %s" % os.path.abspath(OUT))
    print("Начальных форм: %d, словоформ: %d" % (total, len(forms)))
    for length in sorted(by_len):
        print("  %d букв: %d" % (length, len(by_len[length])))


if __name__ == "__main__":
    main()